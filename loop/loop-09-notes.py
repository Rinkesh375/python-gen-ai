# ==========================================
# for-else Notes
# ==========================================

# Python allows else with loops.

# Syntax

# for item in iterable:
#     ...
#     if condition:
#         break
# else:
#     ...

# The else belongs to the FOR loop,
# NOT to the if statement.

# else executes ONLY when the loop
# finishes normally.

# If break occurs,
# else is skipped.

# Best use case

# Searching in a list.

# Found
# -> break

# Not Found
# -> else

# Rule to Remember

# break

# ↓

# No else




# No break

# ↓

