# + Operator with Lists
# ---------------------
# The + operator concatenates (joins) two lists.
# It does NOT add the individual elements.
# It creates and returns a NEW list.

# Example:
print([1,2,3] + [3,2,4,6,5])

# Output:
# [1, 2, 3, 3, 2, 4, 6, 5]






# * Operator with Lists
# ---------------------
# The * operator repeats the entire list a specified number of times.
# It does NOT multiply the individual elements.
# It creates and returns a NEW list.

# Example:
print(["Rinkesh"] * 5)

# Output:
# ['Rinkesh', 'Rinkesh', 'Rinkesh', 'Rinkesh', 'Rinkesh']










# * Operator with Lists
# ---------------------
# The * operator repeats the ENTIRE list a specified number of times.
# It does NOT repeat each element individually.
# It creates and returns a NEW list.

# Example:
print(["Rinkesh", "Kumar", "Jha"] * 5)

# Output:
# ['Rinkesh', 'Kumar', 'Jha',
#  'Rinkesh', 'Kumar', 'Jha',
#  'Rinkesh', 'Kumar', 'Jha',
#  'Rinkesh', 'Kumar', 'Jha',
#  'Rinkesh', 'Kumar', 'Jha']